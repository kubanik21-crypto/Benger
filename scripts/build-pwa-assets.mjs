import {syncAppVersion} from './sync-app-version.mjs';
import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { resolve } from 'node:path';
import { PUBLIC_ASSETS } from './public-assets.mjs';
export async function writePwaAssets(directory,{assets:selection=PUBLIC_ASSETS}={}){
 const assets=selection.filter(file=>file!=='sw-assets.js');
 const hash=createHash('sha256');let bytes=0;
 for(const file of assets){hash.update(file);const content=await readFile(resolve(directory,file));bytes+=content.length;hash.update(content);}
 if(bytes>20*1024*1024)throw new Error('Precache przekracza limit 20 MiB. Wydziel katalog core zamiast publikować.');
 const version=hash.digest('hex').slice(0,20);
 await writeFile(resolve(directory,'sw-assets.js'),`// Generated by scripts/build-pwa-assets.mjs\nself.BENGER_VERSION=${JSON.stringify(version)};\nself.BENGER_ASSETS=${JSON.stringify(assets)};\n`);
 return version;
}
if(process.argv[1]===fileURLToPath(import.meta.url)){const directory=process.argv[2]??fileURLToPath(new URL('../',import.meta.url));await syncAppVersion(directory);console.log(await writePwaAssets(directory));}
